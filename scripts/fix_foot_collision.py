#!/usr/bin/env python3
"""Replace OP3's Isaac Lab foot collider (a PhysX convexHull of the full
ankle-roll link mesh, which includes the motor-horn/bracket geometry above
the sole) with two flat box colliders matching MuJoCo's hand-tuned
`class="foot"` geoms in mujoco_menagerie/robotis_op3/op3.xml exactly
(same local body frame, confirmed by the mesh extent lining up with the
MuJoCo box x/z ranges to the millimeter). See STAGE4_PPO_TRAINING.md,
"Confirmed and fixed the collision-geometry lead", for the full writeup.

`robot/op3/usd/**` is gitignored (generated by scripts/convert_urdf_to_usd.py)
so this hand-patch to robotis_op3_physics.usd doesn't itself land in git --
this script is the durable, re-runnable record of the fix. Re-run it any
time the USD gets regenerated from the URDF (idempotent: safe to run twice).

The project's own .venv has no `pxr` (that's an Isaac Sim/Kit extension
module, not a pip package there) -- run this with a throwaway venv instead:
    python3 -m venv /tmp/usdfix_venv && /tmp/usdfix_venv/bin/pip install usd-core
    /tmp/usdfix_venv/bin/python scripts/fix_foot_collision.py
"""
import argparse
from pathlib import Path

try:
    from pxr import PhysxSchema, Usd, UsdGeom, UsdPhysics
    simulation_app = None
except ModuleNotFoundError:
    from isaacsim import SimulationApp

    simulation_app = SimulationApp({"headless": True})
    from pxr import PhysxSchema, Usd, UsdGeom, UsdPhysics


PROJECT_ROOT = Path(__file__).resolve().parent.parent
USD_DIR = PROJECT_ROOT / "robot" / "op3" / "usd"
PHYSICS_USD = USD_DIR / "configuration" / "robotis_op3_physics.usd"
ROOT_USD = USD_DIR / "robotis_op3.usd"

# (link, mesh_name, [(center_xyz, half_extent_xyz), ...]) -- values copied
# directly from op3.xml's two <geom class="foot"> boxes per ankle-roll link.
FEET = [
    (
        "l_ank_roll_link", "ll6",
        [
            ((0.024, 0.013, -0.0265), (0.0635, 0.028, 0.004)),
            ((0.024, 0.0125, -0.0265), (0.057, 0.039, 0.004)),
        ],
    ),
    (
        "r_ank_roll_link", "rl6",
        [
            ((0.024, -0.013, -0.0265), (0.0635, 0.028, 0.004)),
            ((0.024, -0.0125, -0.0265), (0.057, 0.039, 0.004)),
        ],
    ),
]

parser = argparse.ArgumentParser()
parser.add_argument(
    "--clear-instanceability",
    action="store_true",
    help="Debug-only: clear instanceable metadata. Normal 512-env training should keep the USD instanceable.",
)
args = parser.parse_args()


def _clear_instanceability(usd_path: Path) -> int:
    stage = Usd.Stage.Open(str(usd_path))
    count = 0
    for prim in stage.Traverse():
        if prim.IsInstanceable():
            prim.SetInstanceable(False)
            count += 1
    stage.GetRootLayer().Save()
    return count


if args.clear_instanceability:
    for usd_path in (ROOT_USD, PHYSICS_USD):
        cleared = _clear_instanceability(usd_path)
        print(f"Cleared instanceability on {cleared} prims in {usd_path}")

stage = Usd.Stage.Open(str(PHYSICS_USD))

contact_count = 0
for prim in stage.Traverse():
    if prim.HasAPI(UsdPhysics.CollisionAPI):
        physx_collision_api = PhysxSchema.PhysxCollisionAPI(prim)
        if not physx_collision_api:
            physx_collision_api = PhysxSchema.PhysxCollisionAPI.Apply(prim)
        physx_collision_api.CreateContactOffsetAttr(0.005)
        physx_collision_api.CreateRestOffsetAttr(0.0)
        contact_count += 1
print(f"Authored PhysX contact/rest offsets on {contact_count} collision prims in {PHYSICS_USD}")

for link, mesh_name, boxes in FEET:
    collider_root = stage.GetPrimAtPath(f"/colliders/{link}")
    assert collider_root.IsValid(), f"missing /colliders/{link}"

    mesh_node = stage.GetPrimAtPath(f"/colliders/{link}/{mesh_name}/node_STL_BINARY_")
    assert mesh_node.IsValid(), f"missing mesh node for {link}"
    approx_attr = mesh_node.GetAttribute("physics:approximation")
    assert approx_attr.Get() in ("convexHull", None), f"unexpected approximation on {link}: {approx_attr.Get()}"
    # Disable the full-mesh convex-hull collider (motor-horn/bracket geometry
    # above the sole makes this a poor/unstable foot-ground contact shape) --
    # keep the mesh itself (and PhysicsCollisionAPI) authored, just off.
    coll_api = UsdPhysics.CollisionAPI(mesh_node)
    coll_api.GetCollisionEnabledAttr().Set(False)

    for i, (center, half_extent) in enumerate(boxes):
        box_path = f"/colliders/{link}/sole_collider_{i}"
        cube = UsdGeom.Cube.Define(stage, box_path)
        cube.CreateSizeAttr(2.0)  # default cube spans [-1, 1] per axis -> half-extent 1
        cube.CreatePurposeAttr("guide")  # matches the mesh collider's own convention (collision-only, not rendered)
        xformable = UsdGeom.Xformable(cube)
        xformable.ClearXformOpOrder()
        xformable.AddTranslateOp().Set(center)
        xformable.AddScaleOp().Set(half_extent)

        coll_api = UsdPhysics.CollisionAPI.Apply(cube.GetPrim())
        coll_api.GetCollisionEnabledAttr().Set(True)
        physx_collision_api = PhysxSchema.PhysxCollisionAPI.Apply(cube.GetPrim())
        physx_collision_api.CreateContactOffsetAttr(0.005)
        physx_collision_api.CreateRestOffsetAttr(0.0)

stage.GetRootLayer().Save()
print("Saved:", PHYSICS_USD)
if simulation_app is not None:
    simulation_app.close()
